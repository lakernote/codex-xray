export type Translator = (
  key: MessageKey,
  variables?: Record<string, string | number>,
) => string;

export function translate(
  locale: Locale,
  key: MessageKey,
  variables: Record<string, string | number> = {},
): string {
  const template = (locale === "en-US" ? messagesEn : messagesZh)[key];
  return template.replace(/\{(\w+)\}/g, (_, name: string) =>
    String(variables[name] ?? `{${name}}`),
  );
}

export function createTranslator(locale: Locale): Translator {
  return (key, variables) => translate(locale, key, variables);
}

const LOCALE_STORAGE_KEY = "codex-xray.locale.v1";

export function readLocale(): Locale {
  try {
    const saved = window.localStorage.getItem(LOCALE_STORAGE_KEY);
    if (saved === "zh-CN" || saved === "en-US") return saved;
  } catch {
    // Use the product default when the preference store is unavailable.
  }
  return "zh-CN";
}

export function writeLocale(locale: Locale): void {
  try {
    window.localStorage.setItem(LOCALE_STORAGE_KEY, locale);
  } catch {
    // Language still applies to the current window.
  }
}
